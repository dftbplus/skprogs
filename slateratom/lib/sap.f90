  !! Susi Lehtola, Lucas Visscher, Eberhard Engel;
  !! Efficient implementation of the superposition of atomic potentials
  !! initial guess for electronic structure calculations
  !! in Gaussian basis sets.
  !!  J. Chem. Phys. 14 April 2020; 152 (14): 144105.
  !! https://doi.org/10.1063/5.0004046
  !!
  !! used data is labeled helfem_large.dirac in the SI of the paper

  use common_accuracy, only: dp
  use common_message, only: error

  implicit none
  private

  public :: sap_start_pot

contains

  !> Compute SAP potential for an atom on a grid.
  subroutine sap_start_pot(abcissa, nuc, v)

    !> numerical integration abcissas
    real(dp), intent(in) :: abcissa(:)

    !> nuclear charge, i.e. atomic number
    integer, intent(in) :: nuc

    !> xc potential on grid for two spin channels v(:, 1) and v(:, 2)
    real(dp), intent(out) :: v(:, :)

    !! exp. index
    integer :: nexp

    !! effective charge
    real(dp), allocatable :: zeff(:)

    !! tabulated SAP data (exponents, coefficients)
    real(dp), allocatable :: sap_data(:, :)

    allocate(zeff, mold=abcissa)
    zeff(:) = 0.0_dp

    v(:,:) = 0.0_dp

    call get_sap_data(nuc, sap_data)

    ! compute effective charge
    do nexp = 1, size(sap_data, dim=1)
      zeff(:) = zeff + sap_data(nexp, 2) * erfc(sqrt(sap_data(nexp, 1)) * abcissa)
    end do

    v(:, 1) = v(:, 1) + zeff / abcissa
    v(:, 2) = v(:, 1)

    deallocate(sap_data)
    deallocate(zeff)

  end subroutine sap_start_pot


